"""Filing package = cover sheet with filing instructions (generated) + the official agency forms, filled in.

Order follows the IRS attachment-sequence numbers: Form 1040/1040-NR, Schedule 1 (seq. 01),
Schedule NEC (7B), Schedule OI (7C); Form 8843 is placed after the federal return; the state
return follows as a separate stapled set.
"""
from __future__ import annotations
import io
import pymupdf
from reportlab.pdfgen import canvas as _canvas
from reportlab.lib.pagesizes import letter
from .base import FormPage, H
from . import official
from .fill import has_template

FS_LABELS = {"single": "Single", "mfj": "Married filing jointly", "mfs": "Married filing separately",
             "hoh": "Head of household", "qss": "Qualifying surviving spouse"}


class _Pager(FormPage):
    def footer(self, form_no, page, total=None):
        c = self.c
        c.setLineWidth(0.8); c.line(36, 34, 576, 34)
        c.setFont("Helvetica", 6.5)
        c.drawString(36, 25, f"TaxPrep filing instructions - page {page} (keep this page; do not mail it)")

    """FormPage that starts a new page instead of running off the bottom."""
    def __init__(self, c, year):
        super().__init__(c)
        self.year, self.page = year, 1

    def need(self, h=20):
        if self.y - h < 50:
            self.footer("instructions", self.page)
            self.c.showPage()
            self.page += 1
            self.y = H - 50

    def text(self, s, **kw):
        self.need(12)
        super().text(s, **kw)

    def section(self, t):
        self.need(40)
        super().section(t)


def _wrap(s, n=118):
    out, line = [], ""
    for w in str(s).split():
        if len(line) + len(w) + 1 > n:
            out.append(line); line = w
        else:
            line = (line + " " + w).strip()
    if line:
        out.append(line)
    return out


def _bullets(p, items, size=7.5):
    for t in items:
        for i, chunk in enumerate(_wrap("• " + t, 116)):
            p.text(chunk if i == 0 else "   " + chunk, size=size, gap=9.5)


def _cover(taxpayer, result, year, included, missing) -> bytes:
    buf = io.BytesIO()
    c = _canvas.Canvas(buf, pagesize=letter)
    c.setTitle(f"Tax Return Filing Package — TY{year}")
    p = _Pager(c, year)
    fed, st = result["federal"], result["state"]
    mail = result.get("mailing") or {}
    p.header("PKG", "Return Summary & Filing Instructions", year, "Prepared with TaxPrep — keep this page for your records",
             sub=f"Prepared for {taxpayer.get('first_name', '')} {taxpayer.get('last_name', '')}")
    p.section("Result")
    fr = fed["lines"]["refund"]
    p.line("FED", f"Federal Form {fed['form']} ({FS_LABELS.get(fed['filing_status'], '')}): "
           + ("refund" if fr >= 0 else "amount you owe"), abs(fr), bold=True)
    if st["form"] != "none":
        sr = st["lines"]["refund"]
        p.line(st["state"], f"{st['state']} Form {st['form']}: " + ("refund" if sr >= 0 else "amount you owe"),
               abs(sr), bold=True)
    else:
        p.text(f"{st['state']}: no state income tax return required.", size=8)

    p.section("Residency determination")
    p.text(result["residency"]["label"], bold=True, size=8.5)
    for chunk in _wrap(result["residency"]["explanation"]):
        p.text(chunk, size=7.5, gap=9.5)

    warnings = (fed.get("warnings") or []) + (st.get("warnings") or [])
    if warnings or missing:
        p.section("Check before you file")
        _bullets(p, warnings)
        _bullets(p, [f"Also attach (not generated by TaxPrep): {m}" for m in missing])

    p.section("How to file by mail")
    steps = [
        "Print single-sided. Check every page against your W-2s, 1099s and 1042-S forms.",
        "Sign and date the federal and state returns in ink (both spouses if filing jointly). Unsigned returns are sent back.",
        "Federal: attach Copy B of each W-2 (and any 1042-S showing withholding) to the front of Form "
        f"{fed['form'].split(' ')[0]}. Put schedules and forms behind it in attachment-sequence order (as printed in this package).",
    ]
    if st["form"] != "none":
        steps.append(f"{st['state']}: attach the state copy (Copy 2) of each W-2 to Form {st['form']}. "
                     "Mail the state return in its own envelope.")
    steps.append("Make a full copy of everything you mail and keep it for at least 3 years.")
    _bullets(p, steps, size=8)

    def _where(label, usps, pds, owes, pay_note):
        p.text(label, bold=True, size=8.5)
        if usps:
            for chunk in _wrap("USPS (regular or Certified Mail): " + usps, 110):
                p.text("   " + chunk, size=8, gap=10)
        if pds:
            for chunk in _wrap("UPS / FedEx / DHL (street address, all returns): " + pds, 110):
                p.text("   " + chunk, size=8, gap=10)
        if owes and pay_note:
            for chunk in _wrap("Payment: " + pay_note, 110):
                p.text("   " + chunk, size=7.5, gap=9.5)

    p.section("Where to send it")
    _where(f"Federal Form {fed['form']}", mail.get("federal"), mail.get("federal_private_delivery"),
           fr < 0, (mail.get("payment") or {}).get("federal"))
    if st["form"] != "none":
        _where(f"{st['state']} Form {st['form']}", mail.get("state"), mail.get("state_private_delivery"),
               st["lines"]["refund"] < 0, (mail.get("payment") or {}).get(st["state"]))

    due = mail.get("due_dates") or {}
    if due:
        p.section("Due dates")
        nr_no_wage = fed["form"] == "1040-NR" and not fed["lines"].get("wages")
        lines = [f"Federal: {due.get('federal_nr_no_wage_withholding') if nr_no_wage else due.get('federal')}"]
        if st["form"] != "none" and due.get(st["state"]):
            lines.append(f"{st['state']}: {due[st['state']]}")
        lines.append("Filing after the due date: if you owe, penalties and interest apply, so file and pay as soon as "
                     "possible. If you are due a refund there is no late-filing penalty, but the refund must be claimed "
                     "within 3 years of the due date.")
        _bullets(p, lines, size=8)

    p.section("How your tax was calculated")
    _bullets(p, fed["explanations"] + st["explanations"])

    p.section("Forms in this package")
    for f in included:
        p.text("• " + f, size=8)
    p.footer("instructions", p.page)
    c.showPage()
    c.save()
    return buf.getvalue()


def _dual_statement(taxpayer, result, year) -> bytes:
    """Dual-status statement page (Pub. 519, ch. 6): nonresident-period details."""
    buf = io.BytesIO()
    c = _canvas.Canvas(buf, pagesize=letter)
    p = _Pager(c, year)
    fed, res = result["federal"], result["residency"]
    p.header("STMT", "Dual-Status Statement — attach to Form 1040", year,
             "Department of the Treasury—Internal Revenue Service",
             sub=f"{taxpayer.get('first_name', '')} {taxpayer.get('last_name', '')}   SSN/ITIN {taxpayer.get('ssn', '')}")
    p.section("Residency")
    p.text(f"Nonresident alien from January 1, {year} to the day before {res.get('residency_start')}; resident alien "
           f"from {res.get('residency_start')} to December 31, {year}.", size=8)
    p.section("Nonresident-period income (Form 1040-NR statement)")
    L = fed["lines"]
    p.line("1a", "Wages earned while a nonresident (effectively connected)", result.get("_wages_nr_period", 0))
    p.line("1k", "Treaty-exempt income (nonresident period)", L.get("treaty_exempt_income", 0))
    p.text("All other income shown on Form 1040 was received while a resident alien.", size=8)
    p.section("Notes")
    for t in ["Dual-status return: standard deduction not allowed; tax computed on combined taxable income "
              "using the rate schedules for your filing status.",
              "If you are married to a U.S. citizen/resident you may instead elect to be treated as a resident for "
              "the whole year and file jointly (IRC 6013(g)/(h)) — not prepared here."]:
        for chunk in _wrap(t):
            p.text(chunk, size=7.5, gap=9.5)
    p.signature()
    p.footer("STMT", 1, 1)
    c.showPage(); c.save()
    return buf.getvalue()


def build_package(taxpayer: dict, profile: dict, result: dict, year: int = 2025) -> bytes:
    fed, st, res = result["federal"], result["state"], result["residency"]
    out = pymupdf.open()
    included, missing = [], []
    parts: list[pymupdf.Document] = []

    def add(doc, label):
        parts.append(doc); included.append(label)

    mode = fed.get("mode", "resident")
    inc = result.get("_income") or {}
    fed = dict(fed, _dependents_list=inc.get("dependents") or [])
    if mode == "nonresident":
        add(official.form_1040nr(year, taxpayer, fed), "Form 1040-NR")
    else:
        fed_d = dict(fed, _residency_start=res.get("residency_start", ""))
        add(official.form_1040(year, taxpayer, fed_d, dual=(mode == "dual_status")),
            "Form 1040" + (" (Dual-Status Return)" if mode == "dual_status" else ""))
    L = fed["lines"]
    sched = set(fed.get("schedules", []))
    from ..engines.rules_loader import load_rules
    R = load_rules("federal")
    fs = fed["filing_status"]
    # Attachment-sequence order: Sch 1 (01), 1-A, 2 (02), 3 (03), A (07), SE (17), 8863 (50), 8959 (71), 8960 (72)
    if L.get("other_income") or L.get("adjustments"):
        add(official.schedule_1(year, taxpayer, fed), "Schedule 1 (Form 1040)")
    if L.get("sched1a_total"):
        add(official.schedule_1a(year, taxpayer, fed, fs), "Schedule 1-A (Form 1040)")
    if "Schedule 2" in sched:
        add(official.schedule_2(year, taxpayer, fed), "Schedule 2 (Form 1040)")
    if "Schedule 3" in sched or L.get("education_credit") or L.get("sch3_refundable"):
        add(official.schedule_3(year, taxpayer, fed), "Schedule 3 (Form 1040)")
    if "Form 8863" in sched:
        add(official.form_8863(year, taxpayer, fed, inc.get("student")), "Form 8863")
    if "Schedule 8812" in sched:
        add(official.schedule_8812(year, taxpayer, fed), "Schedule 8812 (Form 1040)")
    if L.get("deduction_type") == "itemized" and L.get("deduction"):
        if mode == "nonresident":
            add(official.schedule_a_nr(year, taxpayer, fed), "Schedule A (Form 1040-NR)")
        else:
            add(official.schedule_a(year, taxpayer, fed), "Schedule A (Form 1040)")
    if "Schedule B" in sched:
        add(official.schedule_b(year, taxpayer, inc, fed), "Schedule B (Form 1040)")
    if "Schedule C" in sched and inc.get("business"):
        add(official.schedule_c(year, taxpayer, inc["business"]), "Schedule C (Form 1040)")
    if "Schedule D" in sched:
        add(official.schedule_d(year, taxpayer, inc, fed), "Schedule D (Form 1040)")
    if "Form 8949" in sched and inc.get("sales"):
        add(official.form_8949(year, taxpayer, inc["sales"]), "Form 8949")
    if mode == "nonresident":
        if L.get("nec_tax"):
            add(official.schedule_nec(year, taxpayer, fed), "Schedule NEC (Form 1040-NR)")
        add(official.schedule_oi(year, taxpayer, profile, fed, res), "Schedule OI (Form 1040-NR)")
    if L.get("se_tax"):
        add(official.schedule_se(year, taxpayer, fed, R["self_employment"]["ss_wage_base"]), "Schedule SE (Form 1040)")
    if "Form 8959" in sched:
        add(official.form_8959(year, taxpayer, fed, R["additional_medicare"]["threshold"][fs]), "Form 8959")
    if "Form 8960" in sched:
        add(official.form_8960(year, taxpayer, fed, R["niit"]["magi_threshold"][fs]), "Form 8960")
    if "Form 8833" in sched:
        add(official.form_8833(year, taxpayer, fed, result.get("_payers", "")), "Form 8833")
    if mode == "dual_status":
        doc = pymupdf.open("pdf", _dual_statement(taxpayer, dict(result, _wages_nr_period=result.get("_wages_nr_period", 0)), year))
        add(doc, "Dual-status statement")
    if res.get("form_8843_required"):
        add(official.form_8843(year, taxpayer, profile, res), "Form 8843")
    if L.get("owed"):
        add(official.form_1040v(year, taxpayer, L["owed"]), "Form 1040-V payment voucher (do not attach; put loose in the envelope with your check)")

    # schedules the engine says are needed but that are not generated here
    generated = {"Schedule 1", "Schedule 1-A", "Schedule 2", "Schedule 3", "Schedule A", "Schedule A (Form 1040-NR)",
                 "Schedule NEC (Form 1040-NR)", "Schedule OI (Form 1040-NR)", "Schedule SE", "Form 8959", "Form 8960",
                 "Form 8833", "Form 1040-NR (dual-status statement)", "Schedule 8812", "Schedule B", "Schedule D", "Form 8949", "Form 8863"}
    if inc.get("business"):
        generated.add("Schedule C")
    for s_ in fed.get("schedules", []):
        if s_ not in generated:
            missing.append(s_)

    if st["form"] != "none":
        ca_in = {"dependents": result.get("_dependents", 0), "state_wages": result.get("_state_wages", 0),
                 "health_coverage": profile.get("health_coverage", True), "std": result.get("_state_std", 0)}
        if st["state"] == "CA":
            if st["form"] == "540":
                add(official.ca_540(year, taxpayer, fed, st, ca_in), "California Form 540")
            else:
                add(official.ca_540nr(year, taxpayer, fed, st, ca_in), "California Form 540NR")
            if abs(st["lines"].get("ca_agi", 0) - L["agi"]) >= 1 or st["form"] == "540NR":
                missing.append("California Schedule CA (" + ("540" if st["form"] == "540" else "540NR") +
                               ") — shows the adjustments on lines 14/16")
        elif st["state"] == "NY":
            if st["form"] == "IT-201":
                add(official.ny_it201(year, taxpayer, fed, st, ca_in), "New York Form IT-201")
            else:
                add(official.ny_it203(year, taxpayer, fed, st, ca_in), "New York Form IT-203")

    out.insert_pdf(pymupdf.open("pdf", _cover(taxpayer, result, year, included, missing)))
    for d in parts:
        out.insert_pdf(d)
    out.set_metadata({"title": f"Tax return filing package - TY{year}", "producer": "TaxPrep"})
    return out.tobytes(garbage=3, deflate=True)
